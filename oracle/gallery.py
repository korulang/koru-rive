#!/usr/bin/env python3
"""gallery.py — standing ours|ref contact sheet for koru-rive gates.

Every visual gate gets a pair image Lars can eyeball. Gates and files come
from oracle/gates.json, verdicts from oracle/gate_verdicts.json (written by
run_gates.py). Output: oracle/images/pair_<gate>.png + oracle/gallery.html.

Usage: uv run --with pillow --with numpy python gallery.py
"""
import html, os, sys
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.abspath(__file__))
IMG = os.path.join(ROOT, "images")

# The gate list, the files each gate compares, and the verdicts all come from
# files, not from this script: oracle/gates.json names both images explicitly
# (oracle/images/ only -- no globbing, no /tmp, no newest-mtime-wins) and
# oracle/gate_verdicts.json is written by run_gates.py. Nobody types PASS.
import json

def load_gates():
    gates = json.load(open(os.path.join(ROOT, "gates.json")))
    vp = os.path.join(ROOT, "gate_verdicts.json")
    if not os.path.isfile(vp):
        sys.exit("gallery: oracle/gate_verdicts.json missing -- run oracle/run_gates.py first")
    verdicts = {v["gate"]: v for v in json.load(open(vp))}
    out = []
    for g in gates:
        v = verdicts.get(g["gate"])
        if v is None or v["ours"] != g["ours"] or v["ref"] != g["ref"]:
            sys.exit("gallery: verdict for gate %s is missing or was computed on different files "
                     "-- re-run oracle/run_gates.py" % g["gate"])
        note = g["note"] if v["verdict"] == "PASS" else "%s  [failed: %s]" % (g["note"], ", ".join(v["failed"]))
        if v.get("vacuous"):
            note += "  [VACUOUS: both sides ~empty]"
        out.append((g["gate"], os.path.join(IMG, g["ours"]), os.path.join(IMG, g["ref"]), g["comp"], v["verdict"], note))
    return out

def composite(ours_p, ref_p, out_p, label, comp):
    # Match pixel_oracle's --comp handling: a semi-transparent side is
    # flattened over the gate's declared clear colour so the pair shows the
    # rendered appearance, not raw RGB under alpha=0 (which displays black).
    def flat(p):
        im = Image.open(p).convert("RGBA")
        if comp is None:
            return im.convert("RGB")
        bg = Image.new("RGBA", im.size, tuple(comp) + (255,))
        return Image.alpha_composite(bg, im).convert("RGB")
    o, r = flat(ours_p), flat(ref_p)
    h = max(o.height, r.height)
    w = o.width + r.width + 8
    canvas = Image.new("RGB", (w, h + 18), (24, 24, 28))
    dr = ImageDraw.Draw(canvas)
    dr.text((4, 2), "OURS", fill=(255, 255, 255))
    dr.text((o.width + 12, 2), "REF (browser rive_canvas)", fill=(255, 255, 255))
    canvas.paste(o, (0, 18))
    canvas.paste(r, (o.width + 8, 18))
    canvas.save(out_p)
    return (o.width, h)

def main():
    rows, missing = [], []
    for gate, op, rp, comp, verdict, note in load_gates():
        if not os.path.isfile(op) or not os.path.isfile(rp):
            missing.append((gate, op, rp))
            rows.append((gate, None, verdict, note + "  [MISSING: ours=%s ref=%s]" % (os.path.isfile(op), os.path.isfile(rp))))
            continue
        out = os.path.join(IMG, "pair_%s.png" % gate)
        composite(op, rp, out, gate, comp)
        rows.append((gate, "images/pair_%s.png" % gate, verdict, note))
    rows.sort(key=lambda r: r[2] != "PASS")  # stable: PASS block, then FAIL block
    # html
    parts = ["<!doctype html><meta charset=utf-8><title>koru-rive gallery</title>",
             "<style>body{background:#18181c;color:#eee;font:14px/1.5 system-ui;margin:24px}",
             "h1{font-size:20px}h2{margin:28px 0 8px;font-size:15px;color:#9cf}",
             ".g{display:inline-block;margin:0 16px 24px 0;vertical-align:top}",
             ".g img{border:1px solid #444;display:block}",
             ".v{font-weight:600}.PASS{color:#7f7}.FAIL{color:#f77}</style>",
             "<h1>koru-rive — ours | ref gallery</h1<p>Generated by oracle/gallery.py — regenerate after any visual change.</p>"]
    cur = None
    for gate, img, verdict, note in rows:
        v = verdict
        if v != cur:
            cur = v
            parts.append("<h2>%s</h2>" % ("oracle PASS" if v == "PASS" else "oracle FAIL"))
        if img:
            parts.append('<div class=g><img src=%s width=640><div><b>%s</b> <span class="v %s">%s</span><br><small>%s</small></div></div>'
                         % (img, gate, v, verdict, html.escape(note)))
        else:
            parts.append('<div class=g><div><b>%s</b> <span class="v %s">%s</span><br><small>%s</small></div></div>'
                         % (gate, v, verdict, html.escape(note)))
    open(os.path.join(ROOT, "gallery.html"), "w").write("\n".join(parts))

    # GitHub-renderable index: thumbnails link through to the full pairs.
    # .html does not render on github.com; markdown images do.
    THUMB_W = 256
    npass = sum(1 for _, _, v, _ in rows if v == "PASS")
    lines = ["# koru-rive -- ours | ref gallery", "",
             "Generated by `oracle/gallery.py` -- regenerate after any visual change.",
             "Each thumbnail links to the full pair (OURS left, REF right).",
             "", "%d gates: %d PASS, %d FAIL" % (len(rows), npass, len(rows) - npass),
             "", "| | gate | verdict | checks / note |", "|---|---|---|---|"]
    for gate, img, verdict, note in rows:
        if img:
            pair = os.path.join(IMG, os.path.basename(img))
            thumb = os.path.join(IMG, "thumb_%s.png" % gate)
            im = Image.open(pair)
            im = im.resize((THUMB_W, max(1, int(im.height * THUMB_W / im.width))),
                           Image.LANCZOS)
            im.save(thumb)
            cell = "[![%s](images/thumb_%s.png)](images/pair_%s.png)" % (gate, gate, gate)
        else:
            cell = gate
        lines.append("| %s | %s | %s | %s |" % (cell, gate, verdict, note.replace("|", "\\|")))
    open(os.path.join(ROOT, "GALLERY.md"), "w").write("\n".join(lines) + "\n")

    print("gallery.html + GALLERY.md written; %d gates, %d missing assets" % (len(rows), len(missing)))
    for g, o, r in missing:
        print("  missing:", g, "ours=%s ref=%s" % (o, r))

if __name__ == "__main__":
    main()
